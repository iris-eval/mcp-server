/*
 * Renders src/eval/cusum-thresholds.generated.ts: the regression watcher's
 * alarm line and alarm-rate slope for every baseline a stream can first
 * settle at, up to n = MAX_N, from the same seeded simulations the watcher
 * would otherwise run on its first request. With --check it renders to
 * memory and fails when the committed file differs, so the table can never
 * drift from the simulation it stands in for.
 *
 *   npm run cusum:render
 *   npm run cusum:check
 *
 * The keys are split across child processes, one per core; each key's
 * values depend only on its own seed, so the split does not change them.
 */
import { fork } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { availableParallelism } from 'node:os';
import { fileURLToPath } from 'node:url';
import {
  CUSUM_DELTA,
  CUSUM_TARGET_ARL0,
  settlingBaselines,
  simulateAlarmRateSlope,
  simulateEstimatedBaselineThreshold,
} from '../../src/eval/cusum.js';

/** The largest baseline n tabled. At fails = 10 that covers fail rates down to about 0.5%. */
const MAX_N = 2000;
const OUT = fileURLToPath(new URL('../../src/eval/cusum-thresholds.generated.ts', import.meta.url));

type Row = [fails: number, n: number, h: number, theta: number];

function simulate(keys: Array<[number, number]>): Row[] {
  return keys.map(([fails, n]) => {
    const h = simulateEstimatedBaselineThreshold(fails, n, CUSUM_DELTA, CUSUM_TARGET_ARL0);
    return [fails, n, h, simulateAlarmRateSlope(fails, n, CUSUM_DELTA, h)];
  });
}

function render(rows: Row[]): string {
  const lines = rows.map(([fails, n, h, theta]) => `    '${fails}:${n}': [${h}, ${theta}],`);
  return `/*
 * GENERATED by \`npm run cusum:render\` (scripts/cusum/render-thresholds.ts) — do
 * not edit by hand. \`npm run cusum:check\` fails CI when this file differs
 * from what the simulation produces. Read by src/eval/cusum.ts: for each
 * baseline (fails:n) a stream can first settle at, up to n = ${MAX_N}, the
 * estimated-baseline alarm line and the alarm-rate slope θ, exactly as
 * simulateEstimatedBaselineThreshold and simulateAlarmRateSlope return them.
 * A baseline outside the table is simulated on first use, as before.
 */

export const CUSUM_THRESHOLD_TABLE: {
  readonly delta: number;
  readonly targetArl0: number;
  readonly maxN: number;
  readonly lines: Readonly<Record<string, readonly [h: number, theta: number]>>;
} = {
  delta: ${CUSUM_DELTA},
  targetArl0: ${CUSUM_TARGET_ARL0},
  maxN: ${MAX_N},
  lines: {
${lines.join('\n')}
  },
};
`;
}

async function main(): Promise<void> {
  const check = process.argv.includes('--check');
  const keys = settlingBaselines(MAX_N);
  const shards = Math.max(1, Math.min(availableParallelism(), keys.length));
  const script = fileURLToPath(import.meta.url);
  const started = Date.now();
  const parts = await Promise.all(
    Array.from({ length: shards }, (_, s) => {
      const mine = keys.filter((_, i) => i % shards === s);
      return new Promise<Row[]>((resolve, reject) => {
        const child = fork(script, ['--shard'], { stdio: ['ignore', 'inherit', 'inherit', 'ipc'] });
        child.once('message', (rows) => resolve(rows as Row[]));
        child.once('error', reject);
        child.once('exit', (code) => {
          if (code !== 0) reject(new Error(`shard ${s} exited with ${code}`));
        });
        child.send(mine);
      });
    }),
  );
  const byKey = new Map(parts.flat().map((r) => [`${r[0]}:${r[1]}`, r]));
  const rows = keys.map(([fails, n]) => byKey.get(`${fails}:${n}`)!);
  const text = render(rows);
  const secs = ((Date.now() - started) / 1000).toFixed(1);
  if (check) {
    const committed = readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n');
    if (committed !== text) {
      console.error(`cusum:check: ${OUT} differs from the simulation (${rows.length} baselines, ${secs} s). Run npm run cusum:render.`);
      process.exit(1);
    }
    console.log(`cusum:check: ${rows.length} baselines match the simulation (${shards} processes, ${secs} s).`);
    return;
  }
  writeFileSync(OUT, text);
  console.log(`cusum:render: wrote ${rows.length} baselines to ${OUT} (${shards} processes, ${secs} s).`);
}

if (process.argv.includes('--shard')) {
  process.once('message', (keys) => {
    process.send!(simulate(keys as Array<[number, number]>), () => process.exit(0));
  });
} else {
  await main();
}
