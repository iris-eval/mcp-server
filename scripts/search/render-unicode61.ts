/*
 * Renders src/storage/unicode61.generated.ts: what SQLite FTS5's
 * `unicode61 remove_diacritics 2` tokenizer, the one the trace search index
 * uses, does with each code point. It asks SQLite itself, one code point at
 * a time in the context "a" + character + "a", read back through fts5vocab:
 *
 *   - a separator splits the word ("a", "a");
 *   - a dropped character is removed from inside the word ("aa"): the
 *     combining accents remove_diacritics strips;
 *   - a folded character becomes another one ("aXa"): case, and the
 *     accents unicode61 removes from precomposed letters;
 *   - anything else is kept as it is.
 *
 * The JavaScript tokenizer in src/storage/search.ts reads this table, so the
 * words a query is split into, the words the search without FTS5 matches
 * and the words a snippet marks are exactly the index's. With --check it
 * renders to memory and fails when the committed file differs.
 *
 *   npm run unicode61:render
 *   npm run unicode61:check
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import Database from 'better-sqlite3';

const OUT = fileURLToPath(new URL('../../src/storage/unicode61.generated.ts', import.meta.url));

function probe(): { version: string; separators: Array<[number, number]>; dropped: number[]; folds: Array<[number, number]> } {
  const db = new Database(':memory:');
  db.exec(`CREATE VIRTUAL TABLE t USING fts5(x, tokenize = 'unicode61 remove_diacritics 2'); CREATE VIRTUAL TABLE v USING fts5vocab(t, 'instance');`);
  const insert = db.prepare('INSERT INTO t (rowid, x) VALUES (?, ?)');
  db.transaction(() => {
    for (let cp = 1; cp <= 0x10ffff; cp += 1) {
      if (cp >= 0xd800 && cp <= 0xdfff) continue;
      insert.run(cp, `a${String.fromCodePoint(cp)}a`);
    }
  })();
  const terms = new Map<number, string[]>();
  for (const row of db.prepare('SELECT doc, term FROM v ORDER BY doc, offset').iterate() as Iterable<{ doc: number; term: string }>) {
    const list = terms.get(row.doc) ?? [];
    list.push(row.term);
    terms.set(row.doc, list);
  }
  const version = (db.prepare('SELECT sqlite_version() AS v').get() as { v: string }).v;
  db.close();

  const separators: Array<[number, number]> = [];
  const dropped: number[] = [];
  const folds: Array<[number, number]> = [];
  for (let cp = 1; cp <= 0x10ffff; cp += 1) {
    if (cp >= 0xd800 && cp <= 0xdfff) continue;
    const t = terms.get(cp) ?? [];
    if (t.length === 2 && t[0] === 'a' && t[1] === 'a') {
      const last = separators[separators.length - 1];
      if (last && last[1] === cp - 1) last[1] = cp;
      else separators.push([cp, cp]);
      continue;
    }
    const chars = t.length === 1 ? Array.from(t[0]) : [];
    if (chars.length === 2 && chars[0] === 'a' && chars[1] === 'a') dropped.push(cp);
    else if (chars.length === 3 && chars[0] === 'a' && chars[2] === 'a') {
      const to = chars[1].codePointAt(0)!;
      if (to !== cp) folds.push([cp, to]);
    } else {
      throw new Error(`U+${cp.toString(16)} tokenized as ${JSON.stringify(t)}: not one of separator, dropped, folded or kept`);
    }
  }
  // Every query word goes to MATCH inside double quotes (search.ts, toFtsQuery): a quote must never be part of a word.
  if (!separators.some(([a, b]) => a <= 0x22 && 0x22 <= b)) throw new Error('unicode61 treats " as part of a word; toFtsQuery would not be safe');
  // The surrogate gap is not a code point: bridge it so a range over it reads as the one run it is.
  for (let i = 0; i + 1 < separators.length; i += 1) {
    if (separators[i][1] === 0xd7ff && separators[i + 1][0] === 0xe000) {
      separators[i][1] = separators[i + 1][1];
      separators.splice(i + 1, 1);
    }
  }
  return { version, separators, dropped, folds };
}

const hex = (n: number) => `0x${n.toString(16)}`;

function render(p: ReturnType<typeof probe>): string {
  const rows = (items: string[], perLine: number) => {
    const lines: string[] = [];
    for (let i = 0; i < items.length; i += perLine) lines.push(`    ${items.slice(i, i + perLine).join(', ')},`);
    return lines.join('\n');
  };
  return `/*
 * GENERATED by \`npm run unicode61:render\` (scripts/search/render-unicode61.ts)
 * from SQLite ${p.version} — do not edit by hand. \`npm run unicode61:check\`
 * fails CI when this file differs from what SQLite's own tokenizer does.
 * What \`unicode61 remove_diacritics 2\` does with each code point, for the
 * tokenizer in src/storage/search.ts: separators split words, dropped code
 * points are removed from inside a word, folds map one code point to
 * another, and every other code point is kept as it is.
 */

export const UNICODE61: {
  readonly sqliteVersion: string;
  /** [first, last] code point ranges, ascending. */
  readonly separators: ReadonlyArray<readonly [number, number]>;
  readonly dropped: readonly number[];
  /** [code point, the code point it folds to], ascending. */
  readonly folds: ReadonlyArray<readonly [number, number]>;
} = {
  sqliteVersion: '${p.version}',
  separators: [
${rows(p.separators.map(([a, b]) => `[${hex(a)}, ${hex(b)}]`), 6)}
  ],
  dropped: [
${rows(p.dropped.map(hex), 10)}
  ],
  folds: [
${rows(p.folds.map(([a, b]) => `[${hex(a)}, ${hex(b)}]`), 6)}
  ],
};
`;
}

const text = render(probe());
if (process.argv.includes('--check')) {
  const committed = readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n');
  if (committed !== text) {
    console.error(`unicode61:check: ${OUT} differs from what SQLite's tokenizer does. Run npm run unicode61:render.`);
    process.exit(1);
  }
  console.log('unicode61:check: the table matches SQLite\'s tokenizer.');
} else {
  writeFileSync(OUT, text);
  console.log(`unicode61:render: wrote ${OUT}.`);
}
