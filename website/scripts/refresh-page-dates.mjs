#!/usr/bin/env node
// Writes src/lib/page-dates.ts: the last git edit date of every static
// route's page.tsx. The sitemap emits it as <lastmod> and the learn pages as
// JSON-LD dateModified, so a crawler sees when a page actually changed
// instead of when the site was last built.
//
// Run from website/ after editing any page, then commit the result:
//
//   node scripts/refresh-page-dates.mjs
//
// It is deliberately not a build step. It needs the full git history, and
// Vercel builds from a shallow clone with no .git directory — a build-time
// lookup would silently fall back to "today", which is the defect this file
// replaces (every URL used to carry `new Date()` as its lastmod).

import { execFileSync } from "node:child_process";
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const website = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const appDir = join(website, "src", "app");
const outFile = join(website, "src", "lib", "page-dates.ts");

function* pageFiles(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      // Dynamic segments ([slug]) take their dates from content, and API
      // routes are not pages.
      if (entry.name.startsWith("[") || entry.name === "api") continue;
      yield* pageFiles(full);
    } else if (entry.name === "page.tsx") {
      yield full;
    }
  }
}

const routes = [];
for (const file of pageFiles(appDir)) {
  const rel = relative(appDir, dirname(file)).split(sep).join("/");
  const route = rel === "" ? "/" : `/${rel}`;
  const date = execFileSync("git", ["log", "-1", "--format=%as", "--", file], {
    cwd: website,
    encoding: "utf8",
  }).trim();
  if (!/^\d{4}-\d{2}-\d{2}$/.test(date)) {
    throw new Error(`No git date for ${file} — untracked file or shallow clone?`);
  }
  routes.push([route, date]);
}
routes.sort(([a], [b]) => a.localeCompare(b));

const entries = routes.map(([route, date]) => `  "${route}": "${date}",`).join("\n");

writeFileSync(
  outFile,
  `// GENERATED by scripts/refresh-page-dates.mjs — do not edit by hand.
//
// Last git edit date of each static route's page.tsx. The sitemap emits it
// as <lastmod> and the learn pages as JSON-LD dateModified, so a crawler
// sees when a page changed rather than when the site was last built.
//
// Refresh after editing any page (needs full git history, so run it locally
// and commit the result — Vercel's shallow clone cannot):
//
//   cd website && node scripts/refresh-page-dates.mjs

export const PAGE_LAST_MODIFIED = {
${entries}
} as const;

export type StaticRoute = keyof typeof PAGE_LAST_MODIFIED;
`,
);

console.log(`wrote ${relative(website, outFile)} (${routes.length} routes)`);
