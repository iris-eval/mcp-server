/*
 * The session reader, on a log written in Claude Code's own format.
 *
 * Every entry below has the shape Claude Code 2.1.x writes (the keys and
 * flags were read off real logs; the text is invented): prompts marked by
 * `origin.kind` and older ones that carry none, a slash command and the
 * skill text it expands into, a shell command run with `!`, a task
 * notification, a message from another session, a compaction summary, a
 * sub-agent's entries, a response split across entries that repeat its
 * usage, a tool that failed, an interrupt, an API error, a line cut short,
 * and a turn the log ends in the middle of.
 */
import { afterEach, describe, expect, it } from 'vitest';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { captureOfTurn, readClaudeCodeSession, traceBodyOfTurn, type SessionTurn } from '../../../src/sessions/claude-code.js';
import { ingestTraceSchema } from '../../../src/dashboard/validation.js';
import { EvalEngine } from '../../../src/eval/engine.js';
import { defaultConfig } from '../../../src/config/defaults.js';

const SID = '0f6c3a52-1111-4222-8333-944455556666';
let n = 0;
const at = () => `2026-10-03T10:00:${String(n++).padStart(2, '0')}.000Z`;
const user = (content: unknown, extra: Record<string, unknown> = {}) => ({ type: 'user', isSidechain: false, sessionId: SID, timestamp: at(), message: { role: 'user', content }, ...extra });
const human = (text: string, promptId: string) => user(text, { promptId, promptSource: 'typed', origin: { kind: 'human' } });
const said = (id: string, blocks: unknown[], usage = { input_tokens: 10, output_tokens: 5, cache_read_input_tokens: 100 }, extra: Record<string, unknown> = {}) =>
  blocks.map((b) => ({ type: 'assistant', isSidechain: false, sessionId: SID, timestamp: at(), message: { id, model: 'claude-opus-5-5', role: 'assistant', content: [b], usage }, ...extra }));
const call = (id: string, name: string, input: unknown) => ({ type: 'tool_use', id, name, input });
const result = (id: string, content: unknown, isError = false) => user([{ type: 'tool_result', tool_use_id: id, content, ...(isError ? { is_error: true } : {}) }], { toolUseResult: {} });

function log(): string {
  n = 0;
  const lines: unknown[] = [
    { type: 'permission-mode', permissionMode: 'default', sessionId: SID },
    // 1. A person asks; the agent reads a file, a test run fails, the agent answers. One response is split across three entries that repeat its usage.
    human('Run the tests and tell me what fails.', 'p-1'),
    ...said('msg-1', [{ type: 'thinking', thinking: '…' }, call('toolu_1', 'Read', { file_path: 'package.json' }), call('toolu_2', 'Bash', { command: 'npm test' })]),
    result('toolu_1', '{"name":"demo"}'),
    result('toolu_2', 'Exit code 1\n 2 failed | 10 passed', true),
    ...said('msg-2', [{ type: 'text', text: 'Two tests fail: the date parser and the retry.' }], { input_tokens: 20, output_tokens: 30, cache_read_input_tokens: 0 }),
    // Host bookkeeping between turns, never a prompt.
    { type: 'system', subtype: 'stop_hook_summary', sessionId: SID },
    user('<local-command-caveat>Caveat: the messages below were generated by the user while running local commands.</local-command-caveat>', { isMeta: true }),
    user('<bash-input>git status</bash-input>'),
    user('<bash-stdout>On branch main</bash-stdout><bash-stderr></bash-stderr>'),
    // 2. A slash command (an older log: no origin), then the skill's text the host expands it into.
    user('<command-message>review</command-message>\n<command-name>/review</command-name>\n<command-args>the parser</command-args>'),
    user([{ type: 'text', text: 'Base directory for this skill: …' }], { isMeta: true }),
    ...said('msg-3', [{ type: 'text', text: 'Reviewed.' }]),
    // A compaction summary is the host's, and a sub-agent's entries are its own transcript's.
    user('This session is being continued from a previous conversation…', { isCompactSummary: true, isVisibleInTranscriptOnly: true }),
    { ...said('msg-sub', [call('toolu_sub', 'Grep', { pattern: 'x' })])[0], isSidechain: true },
    // 3. A task notification starts a turn of its own.
    user('<task-notification>\n<task-id>b1</task-id>\n<status>completed</status>\n</task-notification>', { promptId: 'p-3', promptSource: 'system', origin: { kind: 'task-notification' } }),
    ...said('msg-4', [{ type: 'text', text: 'The background run finished; nothing to do.' }]),
    // 4. Another session's message.
    user('Another Claude session sent a message: the review is done.', { promptId: 'p-4', isMeta: true, promptSource: 'system', origin: { kind: 'peer', from: 'a1' } }),
    ...said('msg-5', [{ type: 'text', text: 'Noted.' }]),
    // 5. A person asks, the agent starts a call, the person interrupts.
    human('Rewrite the parser.', 'p-5'),
    ...said('msg-6', [call('toolu_6', 'Edit', { file_path: 'src/date.ts' })]),
    user([{ type: 'text', text: '[Request interrupted by user for tool use]' }]),
    '{"type":"assistant","message":{"id":"msg-cut","model":"claude-opus-5-5","content":[{"type":"text","text":"half a li',
    // 6. An older log's prompt (no origin), answered by an API error the host wrote itself.
    user('Summarise the release notes.'),
    { type: 'assistant', isSidechain: false, sessionId: SID, timestamp: at(), isApiErrorMessage: true, message: { id: 'err-1', model: '<synthetic>', role: 'assistant', content: [{ type: 'text', text: 'API Error: Overloaded' }] } },
    // 7. A person asks, and the agent answers without a tool.
    human('What is 2 + 2?', 'p-7'),
    ...said('msg-8', [{ type: 'text', text: 'Four.' }]),
    // 8. The log ends in the middle of a turn: the call has no result yet.
    human('Deploy it.', 'p-8'),
    ...said('msg-9', [call('toolu_9', 'Bash', { command: 'npm run deploy' })]),
  ];
  return lines.map((l) => (typeof l === 'string' ? l : JSON.stringify(l))).join('\n') + '\n';
}

const dirs: string[] = [];
afterEach(() => {
  for (const d of dirs.splice(0)) rmSync(d, { recursive: true, force: true });
});
async function turns(text = log()): Promise<SessionTurn[]> {
  const dir = mkdtempSync(join(tmpdir(), 'iris-sessions-'));
  dirs.push(dir);
  const path = join(dir, `${SID}.jsonl`);
  writeFileSync(path, text);
  const out: SessionTurn[] = [];
  for await (const t of readClaudeCodeSession(path)) out.push(t);
  return out;
}

describe('readClaudeCodeSession', () => {
  it('finds one turn per prompt, whoever sent it, and none for the host\'s own text', async () => {
    const all = await turns();
    expect(all.map((t) => [t.index, t.origin, t.input])).toEqual([
      [1, 'human', 'Run the tests and tell me what fails.'],
      [2, 'command', '/review the parser'],
      [3, 'task_notification', '<task-notification>\n<task-id>b1</task-id>\n<status>completed</status>\n</task-notification>'],
      [4, 'peer', 'Another Claude session sent a message: the review is done.'],
      [5, 'human', 'Rewrite the parser.'],
      [6, 'human', 'Summarise the release notes.'],
      [7, 'human', 'What is 2 + 2?'],
      [8, 'human', 'Deploy it.'],
    ]);
    expect(all.every((t) => t.session === SID)).toBe(true);
    expect(all[0].promptId).toBe('p-1');
  });

  it('keeps every call with what it returned, a failure as the error the agent received, and the last text as the answer', async () => {
    const [first] = await turns();
    expect(first.toolCalls).toEqual([
      { tool_name: 'Read', input: { file_path: 'package.json' }, call_id: 'toolu_1', output: '{"name":"demo"}' },
      { tool_name: 'Bash', input: { command: 'npm test' }, call_id: 'toolu_2', error: 'Exit code 1\n 2 failed | 10 passed' },
    ]);
    expect(first.output).toBe('Two tests fail: the date parser and the retry.');
    expect(first).toMatchObject({ ended: 'answered', whole: true, model: 'claude-opus-5-5' });
  });

  it('counts a response split across entries once: prompt tokens include the cache', async () => {
    const [first] = await turns();
    // msg-1 (10 + 100 cached, 5) once, not three times; msg-2 (20, 30).
    expect(first.tokenUsage).toEqual({ prompt_tokens: 130, completion_tokens: 35, total_tokens: 165, cache_read_tokens: 100 });
  });

  it('says how each turn ended, and holds as whole only a turn that ended answered with every call answered', async () => {
    const all = await turns();
    expect(all.map((t) => [t.index, t.ended, t.whole])).toEqual([
      [1, 'answered', true],
      [2, 'answered', true],
      [3, 'answered', true],
      [4, 'answered', true],
      [5, 'interrupted', false],
      [6, 'api_error', false],
      [7, 'answered', true],
      [8, 'unanswered', false],
    ]);
    // The host's error message is not the agent's answer, and the sub-agent's call is not the main turn's.
    expect(all[5].output).toBe('');
    expect(all[1].toolCalls).toEqual([]);
  });
});

describe('a turn as a trace', () => {
  it('declares what the log holds in full: every call only for a whole turn, every result only when each call has one', async () => {
    const all = await turns();
    expect(captureOfTurn(all[0], '0.20.0')).toEqual({ name: 'claude-code-session-log', version: '0.20.0', complete: ['input', 'tool_calls', 'tool_outputs'] });
    expect(captureOfTurn(all[6]).complete).toEqual(['input', 'tool_calls', 'tool_outputs']);
    // Interrupted with a call that never returned: neither the calls nor their results.
    expect(captureOfTurn(all[4]).complete).toEqual(['input']);
  });

  it('sends an empty list of calls only for a whole turn, and every body is one the ingest doors accept', async () => {
    const all = await turns();
    expect(traceBodyOfTurn(all[6]).tool_calls).toEqual([]);
    expect(traceBodyOfTurn(all[5])).not.toHaveProperty('tool_calls');
    for (const t of all) expect(ingestTraceSchema.safeParse(traceBodyOfTurn(t, '0.20.0')).success, `turn ${t.index}`).toBe(true);
    expect(traceBodyOfTurn(all[0]).metadata).toEqual({ model: 'claude-opus-5-5', turn: { index: 1, origin: 'human', ended: 'answered', prompt_id: 'p-1', started_at: all[0].startedAt, ended_at: all[0].endedAt } });
  });

  it('is judged as a record the host wrote: a turn with no call meets a requirement for tool calls, and one with calls carries them all', async () => {
    const all = await turns();
    const engine = new EvalEngine(defaultConfig.eval.defaultThreshold, defaultConfig.eval.ruleThresholds, { ...defaultConfig.eval, requiredEvidence: ['tool_calls'] } as never);
    const judge = async (t: SessionTurn) => {
      const b = traceBodyOfTurn(t);
      return engine.evaluateAll({ input: b.input, output: b.output, toolCalls: b.tool_calls, recordedBy: 'harness', capture: b.capture });
    };
    const noCall = await judge(all[6]);
    expect(noCall.verdict).toMatchObject({ state: 'pass' });
    expect(noCall.provenance!.evidence).toMatchObject({ recordedBy: 'harness', capture: { name: 'claude-code-session-log' }, toolCalls: 0 });
    const withCalls = await judge(all[0]);
    expect(withCalls.verdict!.basis).not.toBe('required_evidence_missing');
    expect(withCalls.provenance!.evidence).toMatchObject({ recordedBy: 'harness', carried: expect.arrayContaining(['tool_calls', 'tool_outputs']), toolCalls: 2 });
  });

  it('does not hold a turn whole when a line in it was cut short: it may have been a call', async () => {
    const text = [JSON.stringify(human('What is 2 + 2?', 'p-1')), '{"type":"assistant","message":{"id":"m0","model":"claude-opus-5-5","content":[{"type":"tool_use","id":"t9","na', ...said('m1', [{ type: 'text', text: 'Four.' }]).map((l) => JSON.stringify(l))].join('\n');
    const [t] = await turns(text);
    expect(t).toMatchObject({ ended: 'answered', whole: false, lost: true, toolCalls: [] });
    expect(traceBodyOfTurn(t)).not.toHaveProperty('tool_calls');
    expect(captureOfTurn(t).complete).toEqual(['input']);
  });

  it('keeps a very long tool output as its head and tail, marked truncated', async () => {
    const big = 'BEGIN ' + 'x'.repeat(300_000) + ' END';
    const text = [human('Read the log.', 'p-1'), ...said('m1', [call('t1', 'Read', { file_path: 'a.log' })]), result('t1', big), ...said('m2', [{ type: 'text', text: 'Done reading.' }])]
      .map((l) => JSON.stringify(l))
      .join('\n');
    const [t] = await turns(text);
    const c = t.toolCalls[0];
    expect(c.truncated).toBe(true);
    // Every call, but not every result in full.
    expect(captureOfTurn(t).complete).toEqual(['input', 'tool_calls']);
    expect(String(c.output).length).toBeLessThan(270_000);
    expect(String(c.output).startsWith('BEGIN ')).toBe(true);
    expect(String(c.output).endsWith(' END')).toBe(true);
  });
});

describe('what the review of real logs found', () => {
  const V = '2.1.280';
  const stamped = (text: string, promptId: string) => user(text, { promptId, version: V, promptSource: 'typed', origin: { kind: 'human' } });
  const reply = (id: string, blocks: unknown[], stop: string, usage: Record<string, unknown> = { input_tokens: 10, output_tokens: 5 }) =>
    blocks.map((b) => ({ type: 'assistant', isSidechain: false, sessionId: SID, timestamp: at(), version: V, message: { id, model: 'claude-opus-5-5', role: 'assistant', content: [b], usage, stop_reason: stop } }));
  const read = async (lines: unknown[], stats?: { lostLines: number }) => {
    n = 0;
    const dir = mkdtempSync(join(tmpdir(), 'iris-sessions-'));
    dirs.push(dir);
    const path = join(dir, `${SID}.jsonl`);
    writeFileSync(path, lines.map((l) => (typeof l === 'string' ? l : JSON.stringify(l))).join('\n') + '\n');
    const out: SessionTurn[] = [];
    for await (const t of readClaudeCodeSession(path, stats ? { stats } : {})) out.push(t);
    return out;
  };

  it('answered means the model ended its turn: text before a call the log has not written yet is not an answer, and the output limit is its own ending', async () => {
    const [midway] = await read([stamped('Deploy it.', 'p1'), ...reply('m1', [{ type: 'text', text: 'Deploying now.' }], 'tool_use')]);
    expect(midway).toMatchObject({ ended: 'unanswered', whole: false });
    expect(traceBodyOfTurn(midway)).not.toHaveProperty('tool_calls');
    const [cut] = await read([stamped('Write the report.', 'p1'), ...reply('m1', [{ type: 'text', text: 'The report begins' }], 'max_tokens')]);
    expect(cut).toMatchObject({ ended: 'cut_off', whole: false });
    const [done] = await read([stamped('What is 2 + 2?', 'p1'), ...reply('m1', [{ type: 'text', text: 'Four.' }], 'end_turn')]);
    expect(done).toMatchObject({ ended: 'answered', whole: true });
  });

  it('an unmarked prompt from a version that marks a person\'s prompts was not typed by one', async () => {
    const turns = await read([stamped('Fix the parser.', 'p1'), ...reply('m1', [{ type: 'text', text: 'Fixed.' }], 'end_turn'), user('Continue the loop.', { promptId: 'p2', version: V }), ...reply('m2', [{ type: 'text', text: 'Continuing.' }], 'end_turn')]);
    expect(turns.map((t) => t.origin)).toEqual(['human', 'other']);
    // A slash command's entry, which the host writes unmarked, is still a command.
    const cmd = await read([stamped('Hi.', 'p0'), ...reply('m0', [{ type: 'text', text: 'Hello.' }], 'end_turn'), user('<command-name>/clear</command-name>', { version: V }), { type: 'system', subtype: 'local_command', timestamp: at(), version: V }]);
    expect(cmd.map((t) => [t.origin, t.ended])).toEqual([['human', 'answered'], ['command', 'local']]);
    // A version that marks none is read the older way.
    const old = await read([user('Fix the parser.', { promptId: 'p1', version: '2.0.1' }), ...reply('m1', [{ type: 'text', text: 'Fixed.' }], 'end_turn')]);
    expect(old[0].origin).toBe('human');
  });

  it('a prompt queued mid-turn is named on the turn, and a person\'s means the input is not the only ask', async () => {
    const [t] = await read([
      stamped('Refactor the parser.', 'p1'),
      ...reply('m1', [call('t1', 'Read', { file_path: 'a.ts' })], 'tool_use'),
      result('t1', 'export {}'),
      { type: 'attachment', isSidechain: false, timestamp: at(), version: V, attachment: { type: 'queued_command', commandMode: 'prompt', origin: { kind: 'human' } } },
      { type: 'attachment', isSidechain: false, timestamp: at(), version: V, attachment: { type: 'queued_command', commandMode: 'task-notification', origin: { kind: 'task-notification' } } },
      ...reply('m2', [{ type: 'text', text: 'Done, and I also renamed the file as you asked.' }], 'end_turn'),
    ]);
    expect(t.queued.map((q) => q.origin)).toEqual(['human', 'task_notification']);
    expect(t.whole).toBe(true);
    expect(captureOfTurn(t).complete).toEqual(['tool_calls', 'tool_outputs']);
  });

  it('a result Claude Code cut itself, or reduced to a placeholder, is not declared whole', async () => {
    const [t] = await read([
      stamped('Read the logs.', 'p1'),
      ...reply('m1', [call('t1', 'Bash', { command: 'cat big.log' }), call('t2', 'ToolSearch', { query: 'x' })], 'tool_use'),
      user([{ type: 'tool_result', tool_use_id: 't1', content: 'Output too large; saved. Preview: …' }], { version: V, toolUseResult: { persistedOutputPath: 'C:/tmp/out.txt' } }),
      user([{ type: 'tool_result', tool_use_id: 't2', content: [{ type: 'tool_reference', tool_name: 'Grep' }] }], { version: V, toolUseResult: {} }),
      ...reply('m2', [{ type: 'text', text: 'Read them.' }], 'end_turn'),
    ]);
    expect(t.toolCalls.map((c) => c.truncated)).toEqual([true, true]);
    expect(captureOfTurn(t).complete).toEqual(['input', 'tool_calls']);
  });

  it('a model response after an API error means the turn went on; a local command is its own ending', async () => {
    const [t] = await read([
      stamped('Fix it.', 'p1'),
      { type: 'assistant', isSidechain: false, timestamp: at(), version: V, isApiErrorMessage: true, message: { id: 'e1', model: '<synthetic>', content: [{ type: 'text', text: 'API Error' }] } },
      ...reply('m1', [{ type: 'text', text: 'Fixed after a retry.' }], 'end_turn'),
    ]);
    expect(t).toMatchObject({ ended: 'answered', whole: true });
    const [local] = await read([user('<command-name>/model</command-name>\n<command-args>opus</command-args>', { version: V, promptId: 'p1', origin: { kind: 'human' } }), { type: 'system', subtype: 'local_command', timestamp: at(), version: V }]);
    expect(local).toMatchObject({ origin: 'command', input: '/model opus', ended: 'local' });
  });

  it('a prompt that is only an image is a prompt, and one that held an image does not declare its input whole', async () => {
    const image = { type: 'image', source: { type: 'base64', media_type: 'image/png', data: 'AAAA' } };
    const turns = await read([user([image], { promptId: 'p1', version: '2.0.1' }), ...reply('m1', [{ type: 'text', text: 'A cat.' }], 'end_turn'), user([image, { type: 'text', text: 'And this one?' }], { promptId: 'p2', version: '2.0.1' }), ...reply('m2', [{ type: 'text', text: 'A dog.' }], 'end_turn')]);
    expect(turns.map((t) => [t.input, t.inputPartial, t.output])).toEqual([['', true, 'A cat.'], ['And this one?', true, 'A dog.']]);
    expect(captureOfTurn(turns[1]).complete).toEqual(['tool_calls', 'tool_outputs']);
  });

  it('a line that is not an entry is counted lost, before the first prompt too, and does not stop the read', async () => {
    const stats = { lostLines: 0 };
    const turns = await read(['null', '{"type":"user","message":{"content":"half', stamped('Hello.', 'p1'), '42', ...reply('m1', [{ type: 'text', text: 'Hi.' }], 'end_turn')], stats);
    expect(stats.lostLines).toBe(3);
    expect(turns).toHaveLength(1);
    expect(turns[0]).toMatchObject({ lost: true, whole: false, ended: 'answered' });
  });

  it('a call with no id cannot be matched to its result, so the turn is not whole', async () => {
    const [t] = await read([stamped('Look.', 'p1'), ...reply('m1', [{ type: 'tool_use', name: 'Read', input: {} }], 'tool_use'), ...reply('m2', [{ type: 'text', text: 'Looked.' }], 'end_turn')]);
    expect(t).toMatchObject({ ended: 'answered', whole: false });
  });

  it('the ending is the latest response\'s own: one that carries no stop reason does not inherit an earlier one\'s', async () => {
    const plain = (id: string, blocks: unknown[], stop: string | null) => blocks.map((b) => ({ type: 'assistant', isSidechain: false, timestamp: at(), message: { id, model: 'claude-opus-5-5', content: [b], stop_reason: stop } }));
    const [t] = await read([user('Look.', { promptId: 'p1' }), ...plain('m1', [call('t1', 'Read', {})], 'tool_use'), result('t1', 'ok'), ...plain('m2', [{ type: 'text', text: 'Looked.' }], null)]);
    expect(t).toMatchObject({ ended: 'answered', whole: true });
  });

  it('a queued entry with no mark says what it queued, and a version marks a person\'s prompts only if it marked one', async () => {
    const queue = (mode: string) => ({ type: 'attachment', isSidechain: false, timestamp: at(), version: V, attachment: { type: 'queued_command', commandMode: mode } });
    const [t] = await read([stamped('Run it.', 'p1'), queue('task-notification'), queue('prompt'), ...reply('m1', [{ type: 'text', text: 'Ran it.' }], 'end_turn')]);
    expect(t.queued.map((q) => q.origin)).toEqual(['task_notification', 'human']);
    expect(captureOfTurn(t).complete).not.toContain('input');
    // Only task notifications marked: an unmarked typed prompt is still read the older way.
    const notifications = await read([user('<task-notification>done</task-notification>', { version: V, origin: { kind: 'task-notification' } }), ...reply('m0', [{ type: 'text', text: 'Noted.' }], 'end_turn'), user('Fix the parser.', { version: V }), ...reply('m1', [{ type: 'text', text: 'Fixed.' }], 'end_turn')]);
    expect(notifications.map((x) => x.origin)).toEqual(['task_notification', 'human']);
  });

  it('an origin kind named like a property every object has is other, not the property', async () => {
    const turns = await read([user('Hi.', { version: V, origin: { kind: 'toString' } }), ...reply('m1', [{ type: 'text', text: 'Hello.' }], 'end_turn'), { type: 'attachment', isSidechain: false, timestamp: at(), attachment: { type: 'queued_command', origin: { kind: '__proto__' } } }]);
    expect(turns[0].origin).toBe('other');
    expect(turns[0].queued).toEqual([{ origin: 'other', at: expect.any(String) }]);
  });

  it('a command\'s input is the command, not what the model was given, so it is not declared whole', async () => {
    const [t] = await read([user('<command-name>/review</command-name>\n<command-args>close</command-args>', { version: V, promptId: 'p1', origin: { kind: 'human' } }), user([{ type: 'text', text: 'Base directory for this skill: …' }], { isMeta: true, version: V }), ...reply('m1', [{ type: 'text', text: 'Reviewed.' }], 'end_turn')]);
    expect(t).toMatchObject({ origin: 'command', input: '/review close', inputPartial: true, ended: 'answered' });
    expect(captureOfTurn(t).complete).not.toContain('input');
  });
  it('counts one-hour cache writes, so the cost is estimated at their price', async () => {
    const [t] = await read([stamped('Hi.', 'p1'), ...reply('m1', [{ type: 'text', text: 'Hello.' }], 'end_turn', { input_tokens: 3, output_tokens: 2, cache_creation_input_tokens: 1000, cache_creation: { ephemeral_1h_input_tokens: 1000, ephemeral_5m_input_tokens: 0 } })]);
    expect(t.tokenUsage).toEqual({ prompt_tokens: 1003, completion_tokens: 2, total_tokens: 1005, cache_creation_tokens: 1000, cache_creation_1h_tokens: 1000 });
  });
});
